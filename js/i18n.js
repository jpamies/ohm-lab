let current = 'es';

export function setLang(lang) {
  current = lang === 'ca' ? 'ca' : 'es';
  if (globalThis.document) document.documentElement.lang = current;
  return current;
}

export function getLang() {
  return current;
}

export function t(key, params = {}, lang = current) {
  const table = STRINGS[lang] || STRINGS.es;
  let value = key in table ? table[key] : STRINGS.es[key];
  if (value === undefined) return key;
  if (typeof value !== 'string') return value;
  return value.replace(/\{(\w+)\}/g, (m, name) => (name in params ? String(params[name]) : m));
}

/** Rellena los elementos con data-i18n (texto), data-i18n-ph (placeholder) y data-i18n-aria (aria-label). */
export function applyTranslations(root = document) {
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
  root.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
}
